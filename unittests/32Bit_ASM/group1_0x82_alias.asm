; Opcode 0x82 is the 32-bit-only alias of 0x80 (group 1, r/m8, imm8). Every
; /reg form, hand-encoded because assemblers never emit 0x82.
mov eax, 0x12345678
mov ebx, 0x11
mov ecx, 0xFF
mov edx, 0x0A05
mov edi, 0

db 0x82, 0xC0, 0x10   ; add al, 0x10   -> al = 0x88
db 0x82, 0xCB, 0x22   ; or  bl, 0x22   -> bl = 0x33
db 0x82, 0xE1, 0x0F   ; and cl, 0x0F   -> cl = 0x0F
db 0x82, 0xEA, 0x05   ; sub dl, 0x05   -> dl = 0x00
db 0x82, 0xF6, 0xFF   ; xor dh, 0xFF   -> dh = 0xF5
stc
db 0x82, 0xD0, 0x01   ; adc al, 0x01   -> al = 0x8A
stc
db 0x82, 0xDF, 0x01   ; sbb bh, 0x01   -> bh = 0xFE
db 0x82, 0xF8, 0x8A   ; cmp al, 0x8A   -> ZF
jnz .done
mov edi, 1
.done:
hlt
